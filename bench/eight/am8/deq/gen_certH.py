"""Generate the obligation-H certificate module for a PLCert: sizes the cells (exact replica of the Lean checks),
then writes one `decide +kernel` lemma per knot interval and assembles `CertHNonneg` with `certH_of_parts`.
Usage: gen_certH.py SOURCE OUT.lean MODNAME CERTNAME [IMPORT]
  SOURCE: a window-scope json (fields E, Y) or a Lean data file containing `CERTNAME : PLCert := ⟨D, E, [..]⟩`."""
import sys, json, re, time
from fractions import Fraction as F
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from qcheck import knot, vI, vloC, vloOk, edgeOk
src, out, mod, cname = sys.argv[1:5]; imp = sys.argv[5] if len(sys.argv) > 5 else None
thm = __import__("os").environ.get("THM", f"certH_{cname}")
if src.endswith('.json'):
    J = json.load(open(src)); D = 32; E = int(J['E']); Y = [int(v) for v in J['Y']]
else:
    txt = open(src).read()
    m = re.search(cname + r"\s*:\s*PLCert\s*:=\s*⟨\s*(\d+)\s*,\s*(\d+)\s*,\s*\[([^\]]*)\]\s*⟩", txt)
    D, E = int(m.group(1)), int(m.group(2)); Y = [int(v) for v in m.group(3).replace('\n', ' ').split(',')]
N = D
y = lambda k: F(Y[k], E) if k < len(Y) else F(0)
assert N >= 2 and E > 0 and y(N) == 0 and all(Y[k] <= 0 for k in range(N + 1, len(Y))), "knot sign / data checks"
t0 = time.time(); S = []
for k in range(N - 1):
    s = 1
    while not knot(N, s, k, y(k), y(k + 1))[0]:
        s += 1
        assert s <= 64, ("knot interval does not certify", k)
    S.append(s)
sN = 8
best = min(vI(vloC(N, sN, m))[0] - F(7, 2) * F(1, 2 * N * sN) for m in range(sN))
vlo = F(int(best * 10 ** 6), 10 ** 6)
assert vloOk(N, sN, vlo) and edgeOk(N, y(N - 1), vlo), "edge"
print(f"cells {sum(S)} S {S} vlo {vlo} ({time.time() - t0:.0f}s)", file=sys.stderr)
L = ([f"import {imp}"] if imp else []) + ["import AMW.DEQfH", "",
     f"/-! ###### {mod} — obligation H for `{cname}` (generated by mvt-engine's gen_certH.py)", "",
     f"`ĝ ≤ qf` on `[0, ∞)` for the certificate `{cname}` ({len(Y)} knots at `k/{N}`): {sum(S)} Taylor cells on the",
     f"{N - 1} knot intervals inside the band (`S` per interval), the edge interval `[1 − 1/{N}, 1]` with `vlo = {vlo}` on",
     f"{sN} cells, and the knot signs beyond the band.  Each knot interval is a separate `decide +kernel`. ###### -/", "",
     "set_option maxRecDepth 100000", "", "namespace AMW.DE", ""]
if not imp:
    L.append(f"def {cname} : PLCert := ⟨{D}, {E}, [{', '.join(map(str, Y))}]⟩")
    L.append("")
L.append(f"/-- the cells per knot interval -/\ndef {cname}S : List ℕ := {S}\n")
for k in range(N - 1):
    L.append(f"theorem {cname}_knot{k} : AMW.DQ.knotOk {N} ({cname}S.getD {k} 1) {k} (yQ {cname} {k}) (yQ {cname} {k + 1}) = true := by\n  decide +kernel")
L += [f"theorem {cname}_vlo : AMW.DQ.vloOk {N} {sN} ({vlo.numerator} / {vlo.denominator}) = true := by decide +kernel",
      f"theorem {cname}_edge : AMW.DQ.edgeOk {N} (yQ {cname} {N - 1}) ({vlo.numerator} / {vlo.denominator}) = true := by decide +kernel",
      f"theorem {cname}_YN : {cname}.Y {N} = 0 := by decide +kernel",
      f"theorem {cname}_signs : ((List.range {cname}.n).all fun k => decide (k ≤ {N}) || decide ({cname}.Y k ≤ 0)) = true := by decide +kernel",
      "",
      f"/-- **obligation H** for `{cname}` -/",
      f"theorem {thm} : CertHNonneg {cname} := by",
      f"  refine certH_of_parts (S := {cname}S) (sN := {sN}) (vlo := {vlo.numerator} / {vlo.denominator}) (by decide) (by decide) (by decide)",
      f"    {cname}_vlo {cname}_edge {cname}_YN ?_ ?_",
      f"  · have h := {cname}_signs",
      f"    simp only [List.all_eq_true, List.mem_range, Bool.or_eq_true, decide_eq_true_eq] at h",
      f"    exact h",
      f"  · intro k hk",
      f"    have hk' : k < {N - 1} := hk",
      f"    interval_cases k"]
for k in range(N - 1):
    L.append(f"    · exact ⟨by decide, {cname}_knot{k}⟩")
L += ["", "end AMW.DE", "", f"#print axioms AMW.DE.{thm}", ""]
open(out, 'w').write("\n".join(L)); print(out, len("\n".join(L)), "bytes")
