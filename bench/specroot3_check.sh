#!/bin/bash
# full pre-upload check of SolutionSixW4F.lean against the board's CURRENT record (typh weighted five-point,
# 33649269/50000000) with candidate 1682517/2500000; then kernel replay of the olean. Private spec; shared files untouched.
set -u
cd ~/work/riemann-submission/bench
until mkdir .leanlock 2>/dev/null; do sleep 30; done
trap 'rmdir .leanlock 2>/dev/null' EXIT
mkdir -p specroot3/ChallengeDeps
ln -sf ~/work/riemann-submission/zeta23/.lake/build/lib/lean/ChallengeDeps.olean specroot3/ChallengeDeps.olean
ln -sf ~/work/riemann-submission/zeta23/.lake/build/lib/lean/ChallengeDeps.ilean specroot3/ChallengeDeps.ilean
cat > specroot3/ChallengeDeps/CandidateSpec.lean <<'SPEC'
/- This file is generated by trusted Riemann.fail infrastructure. -/
import ChallengeDeps

noncomputable section

/-- The currently accepted exact lower bound. -/
def currentRecordKappa : ℝ := (33649269 : ℝ) / 50000000

/-- The candidate's exact rational lower bound. -/
def candidateKappa : ℝ := (1682517 : ℝ) / 2500000

end
SPEC
ZP=$(cut -d: -f2- specroot/LEAN_PATH.txt)
LEANBIN=~/.elan/toolchains/leanprover--lean4---v4.33.0-rc2/bin/lean
env LEAN_PATH=$ZP LEAN_NUM_THREADS=2 $LEANBIN -o specroot3/ChallengeDeps/CandidateSpec.olean specroot3/ChallengeDeps/CandidateSpec.lean || exit 1
cp ../SolutionSixW4F.lean specroot3/Cand4F.lean
cat >> specroot3/Cand4F.lean <<'X'

example : currentRecordKappa = (33649269 : ℝ) / 50000000 := rfl
example : candidateKappa = (1682517 : ℝ) / 2500000 := rfl
#print axioms candidate_strict_improvement
#print axioms candidate_critical_line_bound
#print axioms candidate_critical_line_bound_cumulative
X
/usr/bin/time -l env LEAN_PATH=$PWD/specroot3:$ZP LEAN_NUM_THREADS=2 nice -n 10 $LEANBIN -o specroot3/Cand4F.olean specroot3/Cand4F.lean > specroot3/build4F.log 2>&1
echo "BUILD EXIT $?" >> specroot3/build4F.log
/usr/bin/time -l env LEAN_PATH=$PWD/specroot3:$ZP LEAN_NUM_THREADS=2 nice -n 10 $LEANBIN --run ../zeta23/comparator/Solution/ReplayHarness.lean specroot3/Cand4F.olean > specroot3/replay4F.log 2>&1
echo "REPLAY EXIT $?" >> specroot3/replay4F.log
