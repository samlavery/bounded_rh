#!/usr/bin/env bash
# Generate the theorem files from the verbatim walk statements in ../SolutionSixW7.lean.
#   Bench{V}.lean          all sampled theorems, profiler on (per-declaration kernel time)
#   per/{V}_<wk>.lean      one theorem per file (for /usr/bin/time wall time and peak memory)
#   per/Empty_{V}.lean     imports only (process baseline)
# Usage: ./gen.sh [variants...]   default: A B C P0 P1 P2
set -eu
cd "$(dirname "$0")"
S=../SolutionSixW7.lean
SAMPLE=${SAMPLE:-"wk0 wk5 wk13 wk14 wk15 wk18 wk21 wk22 wk27 wk46"}
VARIANTS=${*:-"A B C P0 P1 P2"}
mk() { v=$1; shift; out=$1; shift; prof=$1; shift
  { printf -- '-- generated by gen.sh: sampled walk theorems (verbatim statements from ../SolutionSixW7.lean), variant %s\nimport BenchData\nimport Bench%sDefs\n\nset_option Elab.async false\n%s\nnamespace Zeta23Ext.Bridge.ThreePoint.SixW7Data\n\nopen Zeta23Ext.Bridge.ThreePoint Zeta23Ext.Bridge.ThreePoint.SixW7\n\nset_option maxRecDepth 100000\n\n' "$v" "$v" "$prof"
    for w in "$@"; do grep "^theorem $w : SixW7.walk table bits .* := by decide +kernel$" $S; echo; done
    echo 'end Zeta23Ext.Bridge.ThreePoint.SixW7Data'; } > "$out"; }
mkdir -p per
for v in $VARIANTS; do
  mk "$v" "Bench$v.lean" $'set_option profiler true\nset_option profiler.threshold 1\n' $SAMPLE
  mk "$v" "per/Empty_$v.lean" ''
  for w in $SAMPLE; do mk "$v" "per/${v}_$w.lean" '' "$w"; done
done
