#!/usr/bin/env bash
# buildonly_rec.sh SRC.lean MOD NUM DEN RNUM RDEN ROOT: the build half of pyr/private_check_rec.sh (same spec template,
# same LEAN_PATH, same flags), no kernel replay.  Holds the shared lock throughout.
set -u
cd ~/work/riemann-submission/bench
SRC=$1; MOD=$2; NUM=$3; DEN=$4; RNUM=$5; RDEN=$6; ROOT=$7
until mkdir .leanlock 2>/dev/null; do echo "[buildonly] waiting $(date +%T)"; sleep 30; done
trap 'rmdir .leanlock 2>/dev/null' EXIT
free=$(memory_pressure | tail -1 | grep -oE '[0-9]+'); [ "${free:-0}" -lt 20 ] && { echo "memory pressure ${free}%"; exit 2; }
R=$ROOT
mkdir -p $R/ChallengeDeps
ln -sf ~/work/riemann-submission/zeta23/.lake/build/lib/lean/ChallengeDeps.olean $R/ChallengeDeps.olean
ln -sf ~/work/riemann-submission/zeta23/.lake/build/lib/lean/ChallengeDeps.ilean $R/ChallengeDeps.ilean
cat > $R/ChallengeDeps/CandidateSpec.lean <<SPEC
/- This file is generated by trusted Riemann.fail infrastructure. -/
import ChallengeDeps

noncomputable section

/-- The currently accepted exact lower bound. -/
def currentRecordKappa : ℝ := ($RNUM : ℝ) / $RDEN

/-- The candidate's exact rational lower bound. -/
def candidateKappa : ℝ := ($NUM : ℝ) / $DEN

end
SPEC
ZP=$(cut -d: -f2- specroot/LEAN_PATH.txt)
LEANBIN=~/.elan/toolchains/leanprover--lean4---v4.33.0-rc2/bin/lean
env LEAN_PATH=$ZP LEAN_NUM_THREADS=2 $LEANBIN -o $R/ChallengeDeps/CandidateSpec.olean $R/ChallengeDeps/CandidateSpec.lean || exit 1
cp "$SRC" $R/$MOD.lean
cat >> $R/$MOD.lean <<X

example : currentRecordKappa = ($RNUM : ℝ) / $RDEN := rfl
example : candidateKappa = ($NUM : ℝ) / $DEN := rfl
X
shasum -a 256 "$SRC"
/usr/bin/time -l env LEAN_PATH=$PWD/$R:$ZP LEAN_NUM_THREADS=2 nice -n 10 $LEANBIN -o $R/$MOD.olean $R/$MOD.lean > $R/build_$MOD.log 2>&1
echo "BUILD EXIT $?" >> $R/build_$MOD.log
grep -E "axioms|error|BUILD EXIT| real|peak memory" $R/build_$MOD.log
