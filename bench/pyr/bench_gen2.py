"""Bench variants of the walk design for the sampled SixW7 subtrees (same leaves as BenchC / BenchPY).
Design W: walk by `Nat.rec` on fuel returning a position (0 = failure), the subtree's own bit string (positions from
1) and an explicit root box in each theorem, the box forced at every node, pyramid oracle `lb`.
Env: TAG (default PYW), ORACLE = real | triv, LEAF = full | early (early exit: running sums tested after each term,
terms ordered by weight), PROBE=1 (append `|| true`: failing leaves still evaluate everything and pass).
Writes ../Bench{TAG}Data.lean, ../Bench{TAG}Defs.lean, ../Bench{TAG}.lean."""
import os, sys, re
HERE = os.path.dirname(os.path.abspath(__file__)); BENCH = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
from pyr_table import Pyr, lean_consts
from lean_oracle import oracle_defs
sys.setrecursionlimit(100000); sys.set_int_max_str_digits(0)
exec(open(os.path.join(BENCH, "count_ops.py")).read().split("# SPANS order check")[0].replace('os.path.dirname(os.path.abspath(__file__))', repr(BENCH)))
TAG = os.environ.get("TAG", "PYW"); ORACLE = os.environ.get("ORACLE", "real"); LEAF = os.environ.get("LEAF", "full")
PROBE = os.environ.get("PROBE") == "1"
PE, PB, MAXA = 5, 10, 4
U = 10**10
P = Pyr(PE=PE, PB=PB, MAXA=MAXA, U=U)
SAMPLE = "wk0 wk5 wk13 wk14 wk15 wk18 wk21 wk22 wk27 wk46".split()
LEAVES = []
_leaf = leafCheck
def leafCheck2(b): LEAVES.append(b); return _leaf(b)
leafCheck = leafCheck2
roots = []
for n in SAMPLE:
    m = re.search(rf"theorem {n} : SixW7.walk table bits (\d+) (\d+) (bx\d+) = some (\d+)", sol)
    fuel, pos, b, end = int(m.group(1)), int(m.group(2)), m.group(3), int(m.group(4))
    walk(fuel, pos, bx[b])
    local = ((bits >> pos) & ((1 << (end - pos)) - 1)) << 1        # the subtree's bits, positions from 1
    roots.append((n, fuel, bx[b], local, end - pos + 1))
def tq(b):
    l = b[0::2]; u = b[1::2]
    return [(sum(l[i:j + 1]), sum(u[i:j + 1])) for (i, j) in SPANS]
qs = set()
for b in LEAVES: qs.update(tq(b))
P.need(qs); P.build()
ns = "Zeta23Ext.Bridge.ThreePoint.PyrW"
data = (f"-- generated by pyr/bench_gen2.py ({TAG}): pyramid table for the sampled SixW7 leaves\n"
        f"-- pyramid lower-bound table adapted from five-point-pyramid-2 by typh (Apache-2.0)\nimport BenchCore\n\nuniverse uF\n\nnamespace {ns}\n\n"
        f"def forceN {{α : Sort uF}} (a : ℕ) (k : ℕ → α) : α :=\n  Nat.casesOn (motive := fun _ => α) a (k 0) (fun n => k (Nat.succ n))\n\n"
        + lean_consts(P) + oracle_defs(P) + "\ndef lbT (lo hi : ℕ) : ℕ := Nat.land (Nat.add lo hi) 0\n" + f"\nend {ns}\n")
open(os.path.join(BENCH, f"Bench{TAG}Data.lean"), "w").write(data)
LB = "lb" if ORACLE == "real" else "lbT"
names = [("l0", "u0"), ("l01", "u01"), ("l02", "u02"), ("l03", "u03"), ("l04", "u04"), ("l1", "u1"), ("l12", "u12"), ("l13", "u13"),
         ("l14", "u14"), ("l2", "u2"), ("l23", "u23"), ("l24", "u24"), ("l3", "u3"), ("l34", "u34"), ("l4", "u4")]
C = cN * SC * U
lin = "(Nat.add (Nat.add (Nat.add (Nat.add (Nat.mul 24896 l0) (Nat.mul 42034 l1)) (Nat.mul 46137 l2)) (Nat.mul 42034 l3)) (Nat.mul 24896 l4))"
if LEAF == "full":
    s = "0"
    for w, (a, b) in zip(W, names): s = f"(Nat.add {s} (Nat.mul {w} ({LB} {a} {b})))"
    ineq = f"Nat.ble {C} (Nat.add (Nat.mul {lin} {U}) (Nat.mul {s} {SC}))"
else:
    order = sorted(range(15), key=lambda t: -W[t])
    # running sums s_k = lin*U + SC*(w_1 lb_1 + ... + w_k lb_k), forced; exit as soon as one reaches C
    lines = [f"forceN (Nat.mul {lin} {U}) fun s0 =>", f"bif Nat.ble {C} s0 then true else"]
    for k, t in enumerate(order):
        a, b = names[t]
        lines.append(f"forceN (Nat.add s{k} (Nat.mul {W[t] * SC} ({LB} {a} {b}))) fun s{k + 1} =>")
        lines.append(f"bif Nat.ble {C} s{k + 1} then true else" if k < 14 else "Nat.ble " + str(C) + f" s{k + 1}")
    ineq = "\n  ".join(lines)
if PROBE: ineq = f"({ineq}) || true"
defs = f"""-- generated by pyr/bench_gen2.py: variant {TAG} (walk W, oracle {ORACLE}, leaf {LEAF}{', PROBE' if PROBE else ''})
import BenchCore
import Bench{TAG}Data

namespace {ns}

open Zeta23Ext.Bridge.ThreePoint.SixW7

def leafCheck (b : Box) : Bool :=
  forceN b.l0 fun l0 => forceN b.l1 fun l1 => forceN b.l2 fun l2 => forceN b.l3 fun l3 => forceN b.l4 fun l4 =>
  forceN b.u0 fun u0 => forceN b.u1 fun u1 => forceN b.u2 fun u2 => forceN b.u3 fun u3 => forceN b.u4 fun u4 =>
  forceN (Nat.add l0 l1) fun l01 => forceN (Nat.add l01 l2) fun l02 => forceN (Nat.add l02 l3) fun l03 => forceN (Nat.add l03 l4) fun l04 =>
  forceN (Nat.add l1 l2) fun l12 => forceN (Nat.add l12 l3) fun l13 => forceN (Nat.add l13 l4) fun l14 =>
  forceN (Nat.add l2 l3) fun l23 => forceN (Nat.add l23 l4) fun l24 =>
  forceN (Nat.add l3 l4) fun l34 =>
  forceN (Nat.add u0 u1) fun u01 => forceN (Nat.add u01 u2) fun u02 => forceN (Nat.add u02 u3) fun u03 => forceN (Nat.add u03 u4) fun u04 =>
  forceN (Nat.add u1 u2) fun u12 => forceN (Nat.add u12 u3) fun u13 => forceN (Nat.add u13 u4) fun u14 =>
  forceN (Nat.add u2 u3) fun u23 => forceN (Nat.add u23 u4) fun u24 =>
  forceN (Nat.add u3 u4) fun u34 =>
  {ineq}

/-- the bisection walk: `Nat.rec` on the fuel; the position after the subtree, 0 on failure -/
def walk (bits : ℕ) (fuel : ℕ) : ℕ → Box → ℕ :=
  Nat.rec (motive := fun _ => ℕ → Box → ℕ) (fun _ _ => 0)
    (fun _ ih pos b =>
      bif Nat.testBit bits pos then
        forceN (Nat.land (Nat.shiftRight bits (Nat.add pos 1)) 7) fun ax => forceN (b.mid ax) fun q =>
        forceN (ih (Nat.add pos 4) (b.setHi ax q)) fun p' =>
        bif Nat.beq p' 0 then 0 else ih p' (b.setLo ax q)
      else bif Nat.blt b.u4 b.l0 || leafCheck b then Nat.add pos 1 else 0)
    fuel

end {ns}
"""
open(os.path.join(BENCH, f"Bench{TAG}Defs.lean"), "w").write(defs)
