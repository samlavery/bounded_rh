def tq(b):
    l = b[0::2]; u = b[1::2]
    return [(sum(l[i:j + 1]), sum(u[i:j + 1])) for (i, j) in SPANS]
qs = set()
for b in LEAVES: qs.update(tq(b))
P.need(qs); P.build()
print("table:", P.stats(), "queries", len(qs))
